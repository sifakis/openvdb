"""Writes a copy of nanovdb/tools/cuda/CSG.cuh with timers around the steps of csg::detail::combine and around the
parts of mergePrunedGrids. Every timer synchronizes the stream and adds the time since the previous one to
gCsgStageMs: 0 setup, 1 retain masks, 2 topology, 3 values, 4 invert masks; 5..12 the parts of the topology build.
The header of the repository is not changed. nanovdb_timing.cu, built with -DCSG_STAGE_TIMERS and with the output
directory first on the include path, prints the times.

usage: stage_timers.py <repository>/nanovdb/nanovdb/tools/cuda/CSG.cuh <output dir>
       writes <output dir>/nanovdb/tools/cuda/CSG.cuh
"""
import os
import sys

PREAMBLE = '''// Generated by stage_timers.py: CSG.cuh with timers around its steps. Not part of the library.
#include <chrono>
#include <cuda_runtime.h>
inline double gCsgStageMs[16] = {};
inline std::chrono::steady_clock::time_point gCsgStepLast, gCsgPartLast;
inline void csgTimer(std::chrono::steady_clock::time_point& last, int i, cudaStream_t stream)
{
    cudaStreamSynchronize(stream);
    const auto now = std::chrono::steady_clock::now();
    if (i >= 0) gCsgStageMs[i] += std::chrono::duration<double, std::milli>(now - last).count();
    last = now;
}
'''

STEP = '    csgTimer(gCsgStepLast, %d, stream);\n'
PART = '    csgTimer(gCsgPartLast, %d, stream);\n'

# (text that occurs exactly once in the header, timer line, True to insert before the text and False after it)
MARKS = [
    ('    if (levelSet1.phi.empty() || levelSet2.phi.empty())\n', STEP % -1, True),
    ('    // 1. The active voxels of each input that stay active in the result.\n', STEP % 0, True),
    ('    // 2. The topology of the result.\n', STEP % 1, True),
    ('    // 3. The values of its active voxels; slot 0 holds the background.\n', STEP % 2, True),
    ('    // 4. The invert masks of the result, level by level.\n', STEP % 3, True),
    ('    // todo: the root origins of the result (section 8.3 of CSG-design.md); empty here.\n', STEP % 4, True),
    ('    TopologyBuilder<BuildT, ResourceT> builder(stream, resource);\n\n    // Root: the tiles of both inputs', PART % -1, True),
    ('    builder.uploadProcessedRoot(stream);\n', PART % 5, False),
    ('    builder.allocateInternalMaskBuffers(stream);\n', PART % 6, False),
    ('    builder.countNodes(stream);\n', PART % 7, True),
    ('    builder.countNodes(stream);\n', PART % 8, False),
    ('    cudaCheck(cudaMemcpyAsync(&builder.data()->getGrid(), grid1->data()', PART % 9, True),
    ('    builder.processLowerNodes(stream);\n', PART % 10, False),
    ('    builder.processLeafOffsets(stream);\n', PART % 11, True),
    ('    builder.postProcessGridTree(stream);\n', PART % 12, False),
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source = open(sys.argv[1]).read()
    for text, _, _ in MARKS:
        if source.count(text) != 1:
            sys.exit('stage_timers.py: CSG.cuh changed; this line is no longer there exactly once:\n' + text)
    for text, timer, before in MARKS:
        source = source.replace(text, timer + text if before else text + timer, 1)
    directory = os.path.join(sys.argv[2], 'nanovdb', 'tools', 'cuda')
    os.makedirs(directory, exist_ok=True)
    with open(os.path.join(directory, 'CSG.cuh'), 'w') as out:
        out.write(PREAMBLE + source)


if __name__ == '__main__':
    main()
