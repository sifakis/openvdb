def extremes_over_C(w, N=1200):
    lo, hi = 1e18, -1e18
    arglo = arghi = None
    for i in range(N+1):
        for j in range(i+1):
            x, y, z = 1.0, i/N, j/N
            L = math.sqrt(x*x+y*y+z*z)
            n = (x/L, y/L, z/L)
            d = w[0]*n[0]+w[1]*n[1]+w[2]*n[2]
            if d < lo: lo, arglo = d, n
            if d > hi: hi, arghi = d, n
    return lo, hi, arglo, arghi


