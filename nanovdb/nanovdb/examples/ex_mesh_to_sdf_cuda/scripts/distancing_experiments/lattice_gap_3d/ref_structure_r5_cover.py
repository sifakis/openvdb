def orbit(w):
    import itertools
    out = set()
    for p in itertools.permutations(range(3)):
        for s in itertools.product((1,-1), repeat=3):
            v = tuple(s[k]*w[p[k]] for k in range(3))
            out.add(v)
    return [(a,b,c,math.sqrt(a*a+b*b+c*c)) for (a,b,c) in out]

